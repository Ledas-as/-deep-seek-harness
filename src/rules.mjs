export function validateChinese(text, label, max = 400) {
  if (typeof text !== 'string' || text.trim().length < 4 || text.length > max
      || !/[\u3400-\u9fff]/u.test(text) || /[`\r\n<>]/u.test(text)) {
    throw new Error(`${label}需要是简短的中文自然语言，不要填代码、Markdown 或多行命令。`);
  }
  return text.trim();
}

export function markdownText(text) {
  return String(text).replace(/[\\`*_{}\[\]()<>#!|]/gu, '\\$&');
}
